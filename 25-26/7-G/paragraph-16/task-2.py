# Учні 7-А класу спілкувалися в соцмережі. Петрик зробив
# x дописів, Марічка — y дописів, а кожен із решти учнів —
# по z дописів. Скільки всього було зроблено дописів, якщо
# загалом у спілкуванні брали участь n учнів? Значення
# x, y, z та n вводить користувач.


# Введення даних
n = int(input("Введіть загальну кількість учнів (n): "))
x = int(input("Скільки дописів зробив Петрик (x): "))
y = int(input("Скільки дописів зробила Марічка (y): "))
z = int(input("Скільки дописів зробив кожен з решти учнів (z): "))

# Обчислення
# 1. Рахуємо кількість "решти" учнів (від загальної кількості віднімаємо Петрика та Марічку)
other_students_count = n - 2

# 2. Рахуємо загальну кількість дописів
# (дописи Петрика + дописи Марічки + дописи решти учнів)
total_posts = x + y + (other_students_count * z)

# Виведення результату
print(f"\nЗагалом було зроблено дописів: {total_posts}")
# В одну посудину налили 1 л молока, в іншу — 1 л води.
# З першої посудини у другу перелили склянку молока ємніс-
# тю t мл (t < 1000), а потім таку саму склянку розчину, отри-
# маного в другій посудині, перелили назад у першу. Скільки
# мілілітрів молока в результаті вийшло в розчинах з першої
# та другої посудин? Значення t вводить користувач.


# Введення ємності склянки
t = float(input("Введіть об'єм склянки в мл (t < 1000): "))

# Початкові умови в мл
v_total = 1000  # 1 літр = 1000 мл

# Крок 1: Переливаємо склянку молока в воду
# У другій посудині тепер (1000 + t) мл суміші
# У цій суміші рівно t мл молока
milk_in_vessel2 = t 

# Крок 2: Переливаємо склянку суміші назад у першу
# Концентрація молока в другій посудині: t / (1000 + t)
concentration2 = t / (v_total + t)

# Скільки молока повернулося в першу посудину зі склянкою суміші?
milk_returned = t * concentration2

# Крок 3: Рахуємо фінальну кількість молока
# У першій посудині було (1000 - t), додали те, що повернулося
milk_vessel1 = (v_total - t) + milk_returned

# У другій було t, забрали те, що перелили назад
milk_vessel2 = t - milk_returned

# Виведення результату
print(f"\nМолока в першій посудині: {round(milk_vessel1, 2)} мл")
print(f"Молока в другій посудині: {round(milk_vessel2, 2)} мл")
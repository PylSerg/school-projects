# Білочки та горішки
n = int(input("\nВведіть кількість білочок: "))
m = int(input("Введіть кількість горішків: "))

# Ділимо кількість горішків на кількість білочок
nuts_per_squirrel = m // n

# Знаходимо залишок горішків
remaining_nuts = m % n

# Виводимо результат
print(f"\nКожна білочка отримає по {nuts_per_squirrel} горіхів.")
print(f"Залишилось {remaining_nuts} горіхів.")
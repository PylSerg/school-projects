# Є n білочок та m горіхів, які потрібно розділити порівну між
# білоч ками (значення n та m уводить користувач, m ≥ n).
# По скільки цілих горіхів отримає кожна білочка і скільки го-
# ріхів залишиться?


# Введення даних від користувача
n = int(input("Введіть кількість білочок (n): "))
m = int(input("Введіть кількість горіхів (m): "))

# Обчислення
# Оператор // знаходить цілу частину від ділення
nuts_per_squirrel = m // n

# Оператор % знаходить залишок від ділення
remaining_nuts = m % n

# Виведення результату
print(f"\nКожна білочка отримає по стільки горіхів: {nuts_per_squirrel}")
print(f"Залишиться горіхів: {remaining_nuts}")
# \n - друк з нового рядка
# print(f"") - виводить шаблонний рядок у консоль
# print(f"{a}") - виводить значення змінної а у консоль

print(f"Обчислення периметра прямокутника \n")

a = float(input("Введіть сторону А: "))
b = float(input("Введіть сторону В: "))

p = 2 * ( a + b )

print(f"\nРезультат:\n Периметр прямокутника зі сторонами {a} см та {b} см дорівнює {p} см.")

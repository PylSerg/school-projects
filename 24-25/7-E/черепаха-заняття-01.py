# from turtle import * - імпорт бібліотеки turtle

# bgcolor() - задає колір фону
# setup() - задає розміри вікна
# shape("turtle") - задає форму черепахи
# speed() - задає швидкість черепахи (1-10)
# width() - задає товщину лінії
# color() - задає колір лінії
# done() - закінчує виконання програми

from turtle import *

bgcolor("lightblue")
setup(width=800, height=800)

shape("turtle")
speed(5)

width(10)
color("green")

forward(300)

done()